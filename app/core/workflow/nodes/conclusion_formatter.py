            entity_id = str(hypothesis.get("entity_id") or "").strip()
            if entity_id not in scope_entity_ids:
                continue
            hypothesis_support = [
                str(fact_id)
                for fact_id in hypothesis.get("supporting_fact_ids", [])
                if str(fact_id) in supporting_ids
            ]
