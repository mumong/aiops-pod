    @classmethod
    def _build_authoritative_tool_facts(cls, evidence_data: Dict[str, Any]) -> str:
        """Extract high-signal facts from real tool output for conclusion.

        The conclusion LLM also receives layer hypotheses and RCA summaries. This
        section makes raw Kubernetes facts explicit so hypotheses cannot override
        negative evidence such as ``finalizers: <none>``.
        """
        tool_data = evidence_data.get("tool_data", []) if isinstance(evidence_data, dict) else []
        if not isinstance(tool_data, list):
            return ""

        lines: List[str] = []
        all_text_parts: List[str] = []
        seen = set()
        for item in cls._select_diagnostic_tool_data(tool_data, limit=12):
            if not isinstance(item, dict):
                continue
            ledger = normalize_fact_ledger(item.get("fact_ledger"))
            if ledger is not None and ledger.source == "mcp_canonical":
                continue
            tool = str(item.get("tool", "unknown"))
            if tool.lower() in {"fetch_runbook", "read_context_archive"}:
                continue
            data = str(item.get("data", "") or "")
            if not data.strip():
                continue
            all_text_parts.append(data)
            for fact in cls._extract_priority_fact_lines(tool, data):
                if fact in seen:
                    continue
                seen.add(fact)
                lines.append(f"- {fact}")
                if len(lines) >= 24:
                    break
            if len(lines) >= 24:
                break

        combined = "\n".join(all_text_parts)
        conclusions = cls._derive_authoritative_conclusions(combined)
        if not lines and not conclusions:
            return ""

        result = ["# 权威工具事实（最高优先级）"]
        result.append("以下事实来自真实工具输出，优先级高于 RCA 兜底、layer possible_scenarios 和 runbook 候选场景；候选场景不能覆盖权威工具事实。")
        if lines:
            result.append("工具事实:")
            result.extend(lines)
        if conclusions:
            result.append("强约束结论:")
            result.extend(f"- {item}" for item in conclusions)
        return "\n".join(result) + "\n"

    @staticmethod
    def _select_diagnostic_tool_data(
        tool_data: List[Dict[str, Any]],
        *,
        limit: int,
    ) -> List[Dict[str, Any]]:
        """Bound conclusion input while preserving source-backed evidence."""
        normalized = [
            (index, item)
            for index, item in enumerate(tool_data or [])
            if isinstance(item, dict)
            and tool_item_allows_fact_ledger_projection(item)
        ]

        def priority(entry: tuple[int, Dict[str, Any]]) -> tuple[int, int]:
            index, item = entry
            tool = str(item.get("tool") or "").strip()
            if item.get("fact_ledger") is not None:
                return (0, index)
            if tool in OBSERVABILITY_QUERY_TOOLS:
                return (1, index)
            if tool in {"collect_aiops_case", "get_aiops_case"}:
                return (2, index)
            if tool.startswith("kubectl_"):
                return (3, index)
            return (4, index)

        selected = sorted(normalized, key=priority)[:max(0, int(limit))]
        return [item for _, item in sorted(selected, key=lambda entry: entry[0])]

    @staticmethod
    def _extract_priority_fact_lines(tool: str, data: str) -> List[str]:
        """Keep only compact diagnostic lines that should guide final reporting."""
        patterns = (
            "deletionTimestamp",
            "deletionGracePeriodSeconds",
            "finalizers",
            "terminationGracePeriodSeconds",
            "Termination Grace Period",
            "lifecycle",
            "preStop",
            "sleep ",
            "status:",
            "phase:",
            "Reason:",
            "Exit Code:",
            "OOMKilled",
            "FailedMount",
            "FailedScheduling",
            "ImagePull",
            "ErrImagePull",
            "BackOff",
            "Killing",
            "Stopping container",
            "Ready",
            "Node",
        )
        facts: List[str] = []
        for raw_line in data.splitlines():
            line = " ".join(raw_line.strip().split())
            if not line:
                continue
            if any(pattern in line for pattern in patterns):
                facts.append(f"{tool}: {line[:500]}")
            if len(facts) >= 8:
                break
        return facts

    @staticmethod
    def _derive_authoritative_conclusions(text: str) -> List[str]:
        normalized = " ".join((text or "").split())
        lowered = normalized.lower()
        conclusions: List[str] = []

        if re.search(r"finalizers:\s*<none>", normalized, flags=re.IGNORECASE):
            conclusions.append("排除 finalizer 未清理根因：工具输出明确显示 `finalizers: <none>`。")
        elif re.search(r"finalizers:\s*(\[\s*\]|none|null)(?:\s|$)", normalized, flags=re.IGNORECASE):
            conclusions.append("排除 finalizer 未清理根因：工具输出显示 finalizers 为空。")

        sleep_match = re.search(r"sleep\s+(\d+)", normalized, flags=re.IGNORECASE)
        grace_match = (
            re.search(r"terminationGracePeriodSeconds:\s*(\d+)", normalized)
            or re.search(r"Termination Grace Period:\s*(\d+)s", normalized)
            or re.search(r"deletionGracePeriodSeconds:\s*(\d+)", normalized)
        )
        has_prestop = "prestop" in lowered
        has_killing = "killing" in lowered or "stopping container" in lowered
        if has_prestop and sleep_match:
            conclusions.append(
                f"正向根因事实：preStop hook 执行 `sleep {sleep_match.group(1)}`，删除流程会被 hook 阻塞。"
            )
        if grace_match:
            conclusions.append(
                f"正向根因事实：termination grace/deletion grace 为 {grace_match.group(1)} 秒，Pod 会在该宽限期内保持 Terminating。"
            )
        if has_killing:
            conclusions.append("正向现象事实：kubelet 事件显示正在 `Killing/Stopping container`，说明删除流程已启动但容器终止未完成。")
        if re.search(r"(?:NAME\s+STATUS\s+)?\bnode[\w.-]*\s+Ready\b", normalized, flags=re.IGNORECASE):
            conclusions.append("排除节点不可达主因：节点状态输出包含 `Ready`。")

        return conclusions

    @staticmethod
    def _extract_evidence_stats(evidence_data: Dict[str, Any]) -> Dict[str, Any]:
        """Extract authoritative evidence stats from structured evidence JSON."""
        inv = evidence_data.get("evidence_inventory", []) or []
        if isinstance(evidence_data.get("plan_total"), int):
            plan_total = int(evidence_data.get("plan_total") or 0)
            plan_collected = int(evidence_data.get("plan_collected") or 0)
            plan_completeness = float(evidence_data.get("plan_completeness") or 0)
        else:
            plan_total = len(inv)
            plan_collected = sum(1 for item in inv if isinstance(item, dict) and item.get("collected"))
            plan_completeness = plan_collected / max(plan_total, 1)

        if isinstance(evidence_data.get("environment_evidence_total"), int):
            env_total = int(evidence_data.get("environment_evidence_total") or 0)
            env_collected = int(evidence_data.get("environment_evidence_collected") or 0)
            env_completeness = float(evidence_data.get("environment_evidence_completeness") or 0)
        else:
            measurable = [
                item for item in inv
                if isinstance(item, dict)
                and str(item.get("level", "")).lower() not in {"optional", "reference"}
                and str(item.get("source", "")).lower() not in {"reference", "archive"}
                and "fetch_runbook" not in str(item.get("description", "")).lower()
                and "read_context_archive" not in str(item.get("description", "")).lower()
            ]
            env_total = len(measurable)
            env_collected = sum(1 for item in measurable if item.get("collected"))
            env_completeness = env_collected / max(env_total, 1)

        observability_total = int(evidence_data.get("observability_target_total") or 0)
        observability_collected = int(evidence_data.get("observability_target_collected") or 0)
        observability_completeness = float(
            evidence_data.get("observability_target_completeness") or 0
        )
        diagnostic_total = int(evidence_data.get("diagnostic_evidence_total") or 0)
        diagnostic_collected = int(
            evidence_data.get("diagnostic_evidence_collected") or 0
        )
        diagnostic_completeness = float(
            evidence_data.get("diagnostic_evidence_completeness") or 0
        )
        dimension_coverage = float(
            evidence_data.get("dimension_coverage")
            if evidence_data.get("dimension_coverage") is not None
            else diagnostic_completeness
        )
        dimension_coverage_total = int(
            evidence_data.get("dimension_coverage_total")
            or diagnostic_total
            or observability_total
            or 0
        )
        if evidence_data.get("dimension_coverage_collected") is not None:
            dimension_coverage_collected = int(
                evidence_data.get("dimension_coverage_collected") or 0
            )
        else:
            dimension_coverage_collected = min(
                dimension_coverage_total,
                max(
                    0,
                    round(dimension_coverage_total * dimension_coverage),
                ),
            )
        diagnostic_sufficiency = float(
            evidence_data.get("diagnostic_sufficiency")
            if evidence_data.get("diagnostic_sufficiency") is not None
            else diagnostic_completeness
        )
        diagnostic_sufficiency_label = str(
            evidence_data.get("diagnostic_sufficiency_label") or ""
        )
        tool_events = evidence_data.get("tool_data")
        if not isinstance(tool_events, list) or not tool_events:
            tool_events = evidence_data.get("tool_results")
        if not isinstance(tool_events, list):
            tool_events = []
        executed_tool_count = int(
            evidence_data.get("executed_tool_count")
            if isinstance(evidence_data.get("executed_tool_count"), int)
            else len(tool_events)
        )
        matched_tool_count = int(evidence_data.get("matched_tool_count") or 0)
        unplanned_tool_count = int(evidence_data.get("unplanned_tool_count") or 0)
        if isinstance(evidence_data.get("case_tool_count"), int):
            case_tool_count = int(evidence_data.get("case_tool_count") or 0)
