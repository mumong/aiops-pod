    def _is_diagnosis_structured_conclusion_enabled(self) -> bool:
        """Feature flag for the old machine-consumable diagnosis conclusion path."""
        wf_config = self._get_workflow_config()
        conclusion_cfg = wf_config.get("conclusion", {}) if isinstance(wf_config, dict) else {}
        if isinstance(conclusion_cfg, dict) and "structured_output" in conclusion_cfg:
            return bool(conclusion_cfg.get("structured_output"))

        structured_runtime = wf_config.get("structured_runtime", {}) if isinstance(wf_config, dict) else {}
        if isinstance(structured_runtime, dict):
            nodes = structured_runtime.get("nodes")
            if isinstance(nodes, dict) and "conclusion" in nodes:
                # Backward-compatible escape hatch only: the old path is opt-in
                # through conclusion.structured_output, not the global runtime.
                return False
        return False

    @staticmethod
    def _strip_think_blocks(content: str) -> str:
        """最终报告永远不暴露模型 `<think>` 内容。"""
        if not isinstance(content, str) or not content:
            return content
        cleaned = re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL | re.IGNORECASE)
        cleaned = re.sub(r"^\s+", "", cleaned)
        return cleaned

    @staticmethod
    def _diagnosis_report_validation_errors(content: str) -> List[str]:
        """Reject prompt echoes and structurally broken diagnosis reports."""
        if not isinstance(content, str) or not content.strip():
            return ["empty_report"]

        errors: List[str] = []
        archive_path = "/tmp/aiops/reports/context_archives/"
        prompt_markers = (
            "# 阶段1：问题定位分析",
            "# 阶段2-3：结构化诊断上下文",
            "# 工具采集的原始数据（重要",
            "证据采集统计（系统数据",
            "plan_stats:",
        )
        if any(marker in content for marker in prompt_markers):
            errors.append("internal_prompt_echo")
        if archive_path in content:
            errors.append("archive_path_leak")
        if re.search(r"(?m)^#\s+用户问题\s*$", content):
            errors.append("input_wrapper_echo")
        if content.count("```") % 2:
            errors.append("unbalanced_code_fence")
        remediation_heading = re.search(
            r"(?m)^##\s+[^\n]*结构化修复计划[^\n]*$",
            content,
        )
        if remediation_heading:
            section = content[remediation_heading.end():]
            next_heading = re.search(r"(?m)^##\s+", section)
            if next_heading:
                section = section[:next_heading.start()]
            json_match = re.search(
                r"```json\s*(\{.*?\})\s*```",
                section,
                re.IGNORECASE | re.DOTALL,
            )
            remediation_valid = False
            if json_match:
                try:
                    json.loads(json_match.group(1))
                    remediation_valid = extract_remediation_plan(section) is not None
                except (json.JSONDecodeError, ValueError):
                    remediation_valid = False
            if not remediation_valid:
                errors.append("invalid_remediation_json")

        required_groups = (
            ("diagnosis_overview", ("诊断概览",)),
            ("evidence", ("现象描述", "证据链", "可观测性数据")),
            ("root_cause", ("根因分析", "根因结论")),
            ("remediation", ("修复建议",)),
        )
        for name, candidates in required_groups:
            if not any(candidate in content for candidate in candidates):
                errors.append(f"missing_{name}")
        return errors

