    def _build_tool_data_section(self, thinking_events: list) -> str:
        """
        从 thinking_events 中提取所有节点的工具真实输出数据，
        构建一个文本段落供 conclusion LLM 引用。

        只提取 tool_result 类型且 status=success 的事件。
        """
        parts = []
        seen = set()
        final_observability_event_ids = {
            id(event)
            for event in project_final_observability_events(
                thinking_events
            )
        }
        for ev in thinking_events:
            if ev.get("type") != "tool_result":
                continue
            if ev.get("status") != "success":
                continue
            tool_name = ev.get("tool_name", "unknown")
            if (
                str(tool_name or "").strip().lower()
                in OBSERVABILITY_QUERY_TOOLS
                and id(ev) not in final_observability_event_ids
            ):
                continue
            preview = ev.get("result_preview", "")[:300]  # 限制 preview 长度
            if not preview:
                continue
            # 去重（同一工具同一数据不重复）
            key = f"{tool_name}:{preview[:80]}"
            if key in seen:
                continue
            seen.add(key)
            node = ev.get("node", "")
            parts.append(f"[{node}] {tool_name}: {preview}")

        if not parts:
            return ""
        return "\n".join(parts[:20])  # 最多 20 条，避免超长

