    @staticmethod
    def _summarize_snippet(text: str, limit: int = 120) -> str:
        """将多行工具输出压成单行摘要，便于快速回复。"""
        compact = " ".join((text or "").split())
        if not compact:
            return "-"
        return compact[:limit] + ("..." if len(compact) > limit else "")

