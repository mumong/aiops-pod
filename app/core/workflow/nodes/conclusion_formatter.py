    @staticmethod
    def _enforce_exact_topology_section(
        content: str,
        structured_context: str,
    ) -> str:
        """Replace the model-written topology subsection with exact graph edges."""
        if not isinstance(content, str) or not content:
            return content

        edge_lines = []
        parsed_edges: List[Dict[str, str]] = []
        entities: Dict[str, Dict[str, str]] = {}
        for raw_line in str(structured_context or "").splitlines():
            line = raw_line.strip()
            if not line.startswith("TOPOLOGY_ENTITY "):
                continue
            fields: Dict[str, str] = {}
            try:
                tokens = shlex.split(line)
            except ValueError:
                tokens = line.split()
            for token in tokens[1:]:
                if "=" not in token:
                    continue
                key, value = token.split("=", 1)
                fields[key] = value
            entity_id = fields.get("entity_id")
            if entity_id:
                entities[entity_id] = fields

        def entity_display(entity_id: str) -> str:
            entity = entities.get(entity_id)
            if not entity:
                return f"`{entity_id}`"
            kind = str(entity.get("kind") or "Entity")
            name = str(entity.get("name") or entity_id)
            namespace = str(entity.get("namespace") or "").strip()
            scoped_name = (
                f"{namespace}/{name}"
                if namespace and namespace != "-"
                else name
            )
            return f"{kind} `{scoped_name}`"

        def typed_entity_display(entity_id: str, fallback_kind: str) -> str:
            if entity_id in entities:
                return entity_display(entity_id)
            return f"{fallback_kind} `{entity_id}`"

        for raw_line in str(structured_context or "").splitlines():
            line = raw_line.strip()
            if not line.startswith("- TOPOLOGY relationship="):
                continue
            fields: Dict[str, str] = {}
            for key in (
                "relationship",
                "source",
                "target",
                "source_system",
                "directness",
                "confidence",
            ):
                pattern = (
                    rf'{key}=("[^"]*"|\S+)'
                    if key == "relationship"
                    else rf"{key}=(\S+)"
                )
                match = re.search(pattern, line)
                if not match:
                    continue
                value = match.group(1)
                if value.startswith('"'):
                    try:
                        value = json.loads(value)
                    except json.JSONDecodeError:
                        value = value.strip('"')
                fields[key] = value
            if not all(fields.get(key) for key in ("relationship", "source", "target")):
                continue
            annotations = []
            strength = "/".join(
                value
                for value in (fields.get("directness"), fields.get("confidence"))
                if value
            )
            if strength:
                annotations.append(strength)
            if fields.get("source_system"):
                annotations.append(f"source_system={fields['source_system']}")
            suffix = f" ({'; '.join(annotations)})" if annotations else ""
            edge_lines.append(
                f"- `{fields['relationship']}`: "
                f"{entity_display(fields['source'])} -> "
                f"{entity_display(fields['target'])}{suffix}"
            )
            parsed_edges.append(fields)

        if not edge_lines:
            topology_tools = (
                ConclusionFormatterNode._source_tools_for_dimension(
                    structured_context,
                    "topology",
                )
            )
            return ConclusionFormatterNode._replace_unverified_topology_section(
                content,
                executed=bool(topology_tools),
            )

        topology_explanations: List[str] = []
        pod_to_rs: Dict[str, str] = {}
        rs_to_deployment: Dict[str, str] = {}
        deployments: List[str] = []
        for edge in parsed_edges:
            relationship = edge.get("relationship")
            source = edge.get("source")
            target = edge.get("target")
            if relationship == "Pod --calls--> Pod":
                topology_explanations.append(
                    f"调用方 {entity_display(source)} 的流量进入目标 "
                    f"{typed_entity_display(target, 'Pod')}"
                )
            elif relationship == "Service --selects--> Pod":
                topology_explanations.append(
                    f"{typed_entity_display(source, 'Service')} 将流量选择到 "
                    f"{typed_entity_display(target, 'Pod')}"
                )
            elif relationship == "Pod --owned_by--> ReplicaSet":
                pod_to_rs[source] = target
            elif relationship == "ReplicaSet --owned_by--> Deployment":
                rs_to_deployment[source] = target

        for pod, replica_set in pod_to_rs.items():
            deployment = rs_to_deployment.get(replica_set)
            if not deployment:
                continue
            deployments.append(deployment)
            topology_explanations.append(
                f"目标 {typed_entity_display(pod, 'Pod')} 由 "
                f"{typed_entity_display(deployment, 'Deployment')} 管理，"
                f"中间控制器为 "
                f"{typed_entity_display(replica_set, 'ReplicaSet')}"
            )
        for deployment in dict.fromkeys(deployments):
            topology_explanations.append(
                f"责任边界落在 "
                f"{typed_entity_display(deployment, 'Deployment')} "
                "管理的工作负载"
            )

        topology_summary = (
            "；".join(dict.fromkeys(topology_explanations)) + "。"
            if topology_explanations
            else "当前原始边只足以说明实体关系，尚不能进一步确定责任工作负载。"
        )
        section = [
            "### 拓扑关系（实体与边）",
            (
                "> 以下关系由 "
                + ConclusionFormatterNode._provenance_label(
                    structured_context,
                    ("topology",),
                    fallback="结构化拓扑结果",
                )
                + " 的原始边确定性生成。"
            ),
            *edge_lines,
            f"- **拓扑解读**：{topology_summary}",
            "- **拓扑结论**：仅依据以上原始边判断调用、流量入口和工作负载归属。",
            "",
        ]
        pattern = re.compile(
            r"(?ms)^###\s+拓扑关系（实体与边）\s*$.*?(?=^---\s*$|^#{1,3}\s+|\Z)"
        )
        if not pattern.search(content):
            return content
        return pattern.sub("\n".join(section), content, count=1)

