        lines.append("")

        if columns:
            normalized_columns = [
                c if isinstance(c, dict) else {"key": str(c), "label": str(c)}
                for c in columns
            ]
            labels = [c.get("label", c.get("key", "")) for c in normalized_columns]
            keys = [c.get("key", "") for c in normalized_columns]
            lines.append("## 📈 数据摘要")
            lines.append("")
            lines.append("| " + " | ".join(labels) + " |")
