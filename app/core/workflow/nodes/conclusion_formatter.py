            r"(?:"
            r"(?:(?:memory|内存)\s*)?(?:limit|限制|上限)\s*"
            r"`?\d+(?:\.\d+)?\s*[KMGT]i`?\s*(?:过低|太低|不足)"
            r"|内存限制不足"
            r"|(?:证明\s*)?(?:[Ll]imit|限制)\s*(?:确实)?(?:过小|过低|太低|不足)"
            r"|(?:memory\s+limits?|内存限制)\s*"
            r"[（(]\s*\d+(?:\.\d+)?\s*[KMGT]i\s*[）)]\s*"
            r"低于应用实际运行需求"
            r"|内存配置过小"
            r"|当前\s*(?:[Ll]imit|限制|上限)\s*"
