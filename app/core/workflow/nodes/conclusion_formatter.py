    def _enforce_evidence_stats(self, content: str, evidence_analysis: str) -> str:
        """
        后处理：强制替换 LLM 输出中的证据统计数据为真实值。

        LLM 经常忽略注入的统计数据或自行计算错误的数字。
        此方法用正则匹配报告中的证据完整度行，替换为 evidence_analysis 中的真实数据。
        """
        import re

        try:
            ea = json.loads(evidence_analysis) if evidence_analysis else {}
        except (json.JSONDecodeError, TypeError):
            return content

        stats = self._extract_evidence_stats(ea)
        inv = ea.get("evidence_inventory", [])
        if not stats and not inv:
            return content

        total = int(stats.get("primary_total") or 0)
        collected = int(stats.get("primary_collected") or 0)
        completeness_pct = str(stats.get("primary_completeness_pct") or "0%")
        dimension_total = int(stats.get("dimension_coverage_total") or 0)
        dimension_collected = int(
            stats.get("dimension_coverage_collected") or 0
        )
        dimension_pct = str(stats.get("dimension_coverage_pct") or "0%")
        sufficiency_pct = str(
            stats.get("diagnostic_sufficiency_pct") or "0%"
        )

        real_stat = f"{collected}/{total} ({completeness_pct})"
        dimension_stat = (
            f"{dimension_collected}/{dimension_total} ({dimension_pct})"
        )

        replaced = False

        # 模式1: Markdown 表格行 | **证据完整度** | ... |
        completeness_table_pattern = re.compile(
            r'(\|\s*\*{0,2}证据完整度\*{0,2}\s*\|)\s*[^|]+(\|)',
            re.IGNORECASE
        )
        if completeness_table_pattern.search(content):
            content = completeness_table_pattern.sub(
                rf'\1 {real_stat} \2',
                content,
            )
            replaced = True

        dimension_table_pattern = re.compile(
            r'(\|\s*\*{0,2}可观测性维度覆盖\*{0,2}\s*\|)\s*[^|]+(\|)',
            re.IGNORECASE,
        )
        if dimension_table_pattern.search(content):
            content = dimension_table_pattern.sub(
                rf'\1 {dimension_stat} \2',
                content,
            )
            replaced = True

        sufficiency_table_pattern = re.compile(
            r'(\|\s*\*{0,2}诊断证据充分度\*{0,2}\s*\|)\s*[^|]+(\|)',
            re.IGNORECASE,
        )
        if sufficiency_table_pattern.search(content):
            content = sufficiency_table_pattern.sub(
                rf'\1 {sufficiency_pct} \2',
                content,
            )
            replaced = True

        if (
            dimension_total > 0
            and not dimension_table_pattern.search(content)
        ):
            sufficiency_line_pattern = re.compile(
                r'(?m)^(?P<indent>[ \t]*)(?P<row>'
                r'\|[ \t]*\*{0,2}诊断证据充分度\*{0,2}'
                r'[ \t]*\|[^\n]*)$',
                re.IGNORECASE,
            )
            if sufficiency_line_pattern.search(content):
                content = sufficiency_line_pattern.sub(
                    lambda match: (
                        f"{match.group('indent')}"
                        f"| **可观测性维度覆盖** | {dimension_stat} |\n"
                        f"{match.group('indent')}{match.group('row')}"
                    ),
                    content,
                    count=1,
                )
                replaced = True

        # 模式2: **证据完整度**: ... 或 证据完整度: ...
        completeness_text_pattern = re.compile(
            r'(\*{0,2}证据完整度\*{0,2}\s*[:：])\s*\S+.*',
            re.IGNORECASE
        )
        if completeness_text_pattern.search(content):
            content = completeness_text_pattern.sub(
                rf'\1 {real_stat}',
                content,
            )
            replaced = True

        dimension_text_pattern = re.compile(
            r'(\*{0,2}可观测性维度覆盖\*{0,2}\s*[:：])\s*\S+.*',
            re.IGNORECASE,
        )
        if dimension_text_pattern.search(content):
            content = dimension_text_pattern.sub(
                rf'\1 {dimension_stat}',
                content,
            )
            replaced = True

        sufficiency_text_pattern = re.compile(
            r'(\*{0,2}诊断证据充分度\*{0,2}\s*[:：])\s*\S+.*',
            re.IGNORECASE,
        )
        if sufficiency_text_pattern.search(content):
            content = sufficiency_text_pattern.sub(
                rf'\1 {sufficiency_pct}',
                content,
            )
            replaced = True

        # 模式3: 证据: X/Y 项 或 证据采集: X/Y
        pattern3 = re.compile(
            r'(证据(?:采集)?\s*[:：])\s*\d+\s*/\s*\d+\s*(?:项)?(?:\s*,\s*完整度\s*[:：]?\s*\d+%)?',
            re.IGNORECASE
        )
        if pattern3.search(content):
            content = pattern3.sub(rf'\1 {collected}/{total} 项, 完整度: {completeness_pct}', content)
            replaced = True

        if replaced:
            logger.info("📊 [conclusion] 后处理: 证据统计已强制替换为真实数据 %s", real_stat)
        else:
            logger.debug("📊 [conclusion] 后处理: 未匹配到需要替换的证据统计模式")

        return re.sub(
            r"(?ms)^###\s+采集统计\s*$.*?(?=^#{1,3}\s+|\Z)",
            "",
            content,
        ).rstrip() + "\n"

    def _enforce_collection_statistics_section(
        self,
        content: str,
        evidence_analysis: str,
    ) -> str:
        """Inject one compact, deterministic statistics table into diagnosis reports."""
        if not isinstance(content, str) or not content:
            return content
        try:
            evidence_data = json.loads(evidence_analysis) if evidence_analysis else {}
        except (json.JSONDecodeError, TypeError):
            return content
        if not isinstance(evidence_data, dict) or not evidence_data:
            return content

        stats = self._extract_evidence_stats(evidence_data)
        observability_total = stats["observability_target_total"]
        observability_collected = stats["observability_target_collected"]
        observability_missing = max(
            0,
            observability_total - observability_collected,
        )
        plan_total = stats["plan_total"]
        plan_collected = stats["plan_collected"]
        plan_missing = max(0, plan_total - plan_collected)
        executed_tool_count = stats["executed_tool_count"]
        unplanned_rate = (
            stats["unplanned_tool_count"] / executed_tool_count
            if executed_tool_count
            else 0.0
        )

        rows = []
        if observability_total:
            observability_note = (
                "每个目标均执行成功的 `collect_aiops_case`"
                if not observability_missing
                else f"**仍有 {observability_missing} 个目标未完成实时 case**"
            )
            rows.append(
                "| 异常 Pod 实时采集 | "
                f"{observability_collected}/{observability_total} "
                f"({stats['observability_target_completeness_pct']}) | "
                f"{observability_note} |"
            )
        else:
            rows.append(
                "| 异常 Pod 实时采集 | 未启用 | "
                "本轮未形成 `collect_aiops_case` 目标 |"
            )

        plan_note = (
            "去重且参与完整度计算的计划项"
            if not plan_missing
            else f"**仍有 {plan_missing} 项未执行**"
        )
        rows.extend([
            (
                "| Evidence 可计数计划执行 | "
                f"{plan_collected}/{plan_total} "
                f"({stats['plan_completeness_pct']}) | "
                f"{plan_note} |"
            ),
            (
                "| 工具调用构成 | "
                f"核心 case {stats['case_tool_count']}，"
                f"补充 {stats['supplemental_tool_count']}，"
                f"总计 {executed_tool_count} | "
                f"计划外 {stats['unplanned_tool_count']}（{unplanned_rate:.0%}） |"
            ),
        ])

        if stats["skipped_plan_count"]:
            rows.append(
                "| 充分证据后跳过 | "
                f"{stats['skipped_plan_count']} 项 | "
                "额外 follow-up，未计入已执行项 |"
            )
        if stats["missing_reason_count"]:
            rows.append(
                "| 明确缺失项 | "
                f"{stats['missing_reason_count']} 项 | "
                "**结论必须保留证据限制** |"
            )

        if stats["missing_reason_count"]:
            stop_note = "**仍有明确缺失证据，结论需注明限制**"
        elif observability_missing:
            stop_note = "**存在未采集目标，结论需注明限制**"
        elif plan_missing:
            stop_note = "**存在未完成计划，结论需注明限制**"
        elif stats["collection_stop_reason"] == "采集连续无进展":
            stop_note = "**采集未完整，需检查工具错误或空结果**"
        else:
            stop_note = "已满足当前异常 Pod 的主要证据需求"
        rows.append(
            "| 采集停止原因 | "
            f"{stats['collection_stop_reason']} | {stop_note} |"
        )

        section = "\n".join([
            "### 采集统计",
            "",
            "| 统计项 | 结果 | 说明 |",
            "|---|---|---|",
            *rows,
        ])

        overview = re.search(
            r"(?m)^(?P<heading>#{1,3})\s+.*诊断概览.*$",
            content,
        )
        if not overview:
            return content

        existing_pattern = re.compile(
            r"(?ms)^###\s+采集统计\s*$.*?(?=^#{1,3}\s+|\Z)"
        )
        content = existing_pattern.sub("", content).rstrip() + "\n"

        overview = re.search(
            r"(?m)^(?P<heading>#{1,3})\s+.*诊断概览.*$",
            content,
        )
        overview_level = len(overview.group("heading"))
        next_heading = re.search(
            rf"(?m)^#{{1,{overview_level}}}\s+",
            content[overview.end():],
        )
        insert_at = (
            overview.end() + next_heading.start()
            if next_heading
            else len(content)
        )
        before = content[:insert_at].rstrip()
        after = content[insert_at:].lstrip("\n")
        result = f"{before}\n\n{section}\n\n"
        if after:
            result += after
        return result

    @staticmethod
    def _estimate_tokens(text: str) -> int:
        """粗估 token 数（混合中英文 ~2 chars/token）。

        不需要精确——只用于判断是否需要压缩。
        DeepSeek tokenizer 中文约 1.5 chars/token，英文约 4 chars/token，
        混合取 2 是保守估计，宁可多压缩也不要超限。
        """
        return len(text) // 2
