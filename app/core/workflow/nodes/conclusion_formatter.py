    @staticmethod
    def _repair_invalid_remediation_json(content: str) -> str:
        """Replace only a broken structured remediation section with a safe plan."""
        heading = re.search(
            r"(?m)^##\s+[^\n]*结构化修复计划[^\n]*$",
            content,
        )
        if not heading:
            return content
        remainder = content[heading.end():]
        next_heading = re.search(r"(?m)^##\s+", remainder)
        section_end = (
            heading.end() + next_heading.start()
            if next_heading
            else len(content)
        )
        safe_plan = {
            "remediation_available": False,
            "fix_type": "manual_only",
            "risk_level": "medium",
            "requires_human_approval": True,
            "issue_groups": [],
            "basis": [
                "原始结构化修复计划未通过 JSON 与安全校验，已降级为人工处理。"
            ],
            "actions": [],
            "stop_conditions": [
                "需要人工根据诊断证据确认具体修复动作后再执行"
            ],
        }
        replacement = (
            heading.group(0)
            + "\n\n```json\n"
            + json.dumps(safe_plan, ensure_ascii=False, indent=2)
            + "\n```\n\n"
        )
        return (
            content[:heading.start()]
            + replacement
            + content[section_end:].lstrip("\n")
        )

    @staticmethod
    def _sanitize_observability_evidence_refs(
        content: str,
        structured_context: str,
    ) -> str:
        """Remove model-generated aliases from the observability ref table."""
        if not isinstance(content, str) or not content:
            return content

        ref_pattern = re.compile(
            r"\b(?:metric|log|deepflow|tempo|k8s)-[A-Za-z0-9][A-Za-z0-9_.:/-]*\b"
        )
        valid_refs = set(ref_pattern.findall(str(structured_context or "")))
        lines = content.splitlines()
        in_ref_table = False

        for index, line in enumerate(lines):
            stripped = line.strip()
            if stripped.startswith("|") and "证据 ref" in stripped:
                in_ref_table = True
                continue
            if not in_ref_table:
                continue
            if not stripped.startswith("|"):
                in_ref_table = False
                continue
            if set(stripped.replace("|", "").strip()) <= {"-", ":", " "}:
                continue

            cells = line.split("|")
            if len(cells) < 4:
                continue
            ref_cell = cells[-2]
            candidates = ref_pattern.findall(ref_cell)
            valid_candidates = list(dict.fromkeys(
                ref for ref in candidates if ref in valid_refs
            ))
            ref_text = ref_cell.strip()
            should_replace = (
                (candidates and len(valid_candidates) != len(candidates))
                or (
                    not candidates
                    and bool(ref_text)
                    and ref_text != "见机器可核验附录"
                )
            )
            if should_replace:
                cells[-2] = " 见机器可核验附录 "
                lines[index] = "|".join(cells)
            elif valid_candidates:
                cells[-2] = f" {'<br>'.join(valid_candidates)} "
                lines[index] = "|".join(cells)

        return "\n".join(lines)

    @staticmethod
    def _enforce_observability_dimension_table(
        content: str,
        structured_context: str,
    ) -> str:
        """Make the Tracing table row agree with exact DeepFlow/Tempo facts."""
        if not isinstance(content, str) or not content:
            return content

        def parse_fields(line: str) -> Dict[str, str]:
            fields: Dict[str, str] = {}
            field_starts: List[tuple[str, int, int]] = []
            quote = ""
            escaped = False
            brace_depth = 0
            bracket_depth = 0
            index = 0
            while index < len(line):
                char = line[index]
                if quote:
                    if escaped:
                        escaped = False
                    elif char == "\\":
                        escaped = True
                    elif char == quote:
                        quote = ""
                    index += 1
                    continue
                if char in {'"', "'"}:
                    quote = char
                    index += 1
                    continue
                if char == "{":
                    brace_depth += 1
                    index += 1
                    continue
                if char == "}":
                    brace_depth = max(0, brace_depth - 1)
                    index += 1
                    continue
                if char == "[":
                    bracket_depth += 1
                    index += 1
                    continue
                if char == "]":
                    bracket_depth = max(0, bracket_depth - 1)
                    index += 1
                    continue
                if (
                    brace_depth == 0
                    and bracket_depth == 0
                    and (index == 0 or line[index - 1].isspace())
                ):
                    match = re.match(r"([A-Za-z0-9_.]+)=", line[index:])
                    if match:
                        field_starts.append((
                            match.group(1),
                            index,
                            index + match.end(),
                        ))
                        index += match.end()
                        continue
                index += 1

            for field_index, (key, _key_start, value_start) in enumerate(
                field_starts
            ):
                value_end = (
                    field_starts[field_index + 1][1]
                    if field_index + 1 < len(field_starts)
                    else len(line)
                )
                raw_value = line[value_start:value_end].strip()
                value: Any = raw_value
                if raw_value.startswith(('"', "{", "[")):
                    try:
                        value = json.loads(raw_value)
                    except (json.JSONDecodeError, TypeError):
                        value = raw_value.strip('"')
                fields[key] = (
                    json.dumps(
                        value,
                        ensure_ascii=False,
                        separators=(",", ":"),
                    )
                    if isinstance(value, (dict, list))
                    else str(value)
                )
            return fields

        def expand_structured_value(fields: Dict[str, str]) -> Dict[str, str]:
            parsed: Any = str(fields.get("value") or "").strip()
            for _ in range(2):
                if not isinstance(parsed, str) or not parsed.startswith(("{", "[")):
                    break
                try:
                    parsed = json.loads(parsed)
                except json.JSONDecodeError:
                    break
            if not isinstance(parsed, dict):
                return fields
            expanded = dict(fields)
            for key, value in parsed.items():
                expanded.setdefault(
                    str(key),
                    (
                        json.dumps(
                            value,
                            ensure_ascii=False,
                            separators=(",", ":"),
                        )
                        if isinstance(value, (dict, list))
                        else str(value)
                    ),
                )
            attributes = parsed.get("attributes")
            if isinstance(attributes, dict):
                for key, value in attributes.items():
                    expanded.setdefault(
                        str(key),
                        (
                            json.dumps(
                                value,
                                ensure_ascii=False,
                                separators=(",", ":"),
                            )
                            if isinstance(value, (dict, list))
                            else str(value)
                        ),
                    )
            return expanded

        def enforce_unexecuted_rows(
            report: str,
            execution_states: Dict[str, str],
        ) -> str:
            source_by_dimension = {
                "metrics": "Prometheus",
                "logging": "ES/Filebeat",
                "tracing": "DeepFlow/Tempo",
            }
            label_by_dimension = {
                "metrics": "Metrics",
                "logging": "Logging",
                "tracing": "Tracing",
            }
            lines = report.splitlines()
            for index, line in enumerate(lines):
                for dimension, state in execution_states.items():
                    if state != "not_executed":
                        continue
                    label = label_by_dimension.get(dimension)
                    if not label or not re.match(
                        rf"^\|\s*\*{{0,2}}{label}\*{{0,2}}\s*\|",
                        line.strip(),
                        re.IGNORECASE,
                    ):
                        continue
                    cells = line.split("|")
                    if len(cells) < 7:
                        continue
                    cells[2] = f" {source_by_dimension[dimension]} "
                    cells[3] = " not_executed "
                    cells[4] = " 本轮未执行该维度查询，当前状态未验证，不能解释为数据不存在 "
                    cells[5] = " - "
                    lines[index] = "|".join(cells)
            result = "\n".join(lines)
            if report.endswith("\n"):
                result += "\n"
            return result

        coverage_present = False
        coverage_fields: Dict[str, str] = {}
        execution_fields: Dict[str, str] = {}
        correlations: List[Dict[str, str]] = []
        metric_facts: List[Dict[str, str]] = []
        log_facts: List[Dict[str, str]] = []
        k8s_facts: List[Dict[str, str]] = []
        deepflow_facts: List[Dict[str, str]] = []
        tempo_facts: List[Dict[str, str]] = []
        source_states: Dict[str, Dict[str, str]] = {
            "metrics": {},
            "logging": {},
            "tracing": {},
            "topology": {},
            "kubernetes": {},
        }
        coverage_rank = {
            "present": 4,
            "partial": 3,
            "empty": 2,
            "failed": 1,
            "not_executed": 0,
        }
        for raw_line in str(structured_context or "").splitlines():
            line = raw_line.strip()
            if line.startswith("COVERAGE "):
                fields = parse_fields(line)
                coverage_fields.update(fields)
                coverage_present = coverage_present or any(
                    str(fields.get(key) or "").lower() == "present"
                    for key in ("tracing", "trace")
                )
            elif line.startswith("OBSERVABILITY_EXECUTION "):
                execution_fields.update({
                    key: str(value or "").strip().lower()
                    for key, value in parse_fields(line).items()
                    if key in {"metrics", "logging", "tracing"}
                })
            elif line.startswith("OBSERVABILITY_SOURCE "):
                fields = parse_fields(line)
                dimension = str(fields.get("dimension") or "").strip().lower()
                tool = str(fields.get("tool") or "").strip()
                coverage = str(fields.get("coverage") or "executed").strip().lower()
                if dimension in source_states and tool:
                    previous = source_states[dimension].get(tool, "")
                    if coverage_rank.get(coverage, 0) >= coverage_rank.get(
                        previous,
                        -1,
                    ):
                        source_states[dimension][tool] = coverage
                coverage_key = "logs" if dimension == "logging" else dimension
                previous_coverage = str(coverage_fields.get(coverage_key) or "")
                if coverage_rank.get(coverage, 0) >= coverage_rank.get(
                    previous_coverage,
                    -1,
                ):
                    coverage_fields[coverage_key] = coverage
            elif line.startswith("- TRACE_CORRELATION "):
                correlations.append(parse_fields(line))
            elif line.startswith("- METRIC "):
                metric_facts.append(parse_fields(line))
            elif line.startswith("- LOG "):
                log_facts.append(parse_fields(line))
            elif line.startswith("- K8S_SIGNAL "):
                k8s_facts.append(parse_fields(line))
            elif line.startswith("- DEEPFLOW "):
                deepflow_facts.append(parse_fields(line))
            elif line.startswith("- TEMPO "):
                tempo_facts.append(parse_fields(line))
            elif line.startswith("- QUERY_FACT "):
                fields = expand_structured_value(parse_fields(line))
                if fields.get("unit") or fields.get("sample_count"):
                    metric_facts.append(fields)
                elif (
                    str(fields.get("source_system") or "").strip().lower()
                    in {"elasticsearch", "filebeat"}
                    or str(fields.get("name") or "").strip().lower().startswith("log.")
                ):
                    log_facts.append(fields)
                elif fields.get("trace_id"):
                    source_components = {
                        component
                        for component in re.split(
                            r"[+,/|]",
                            str(fields.get("source_system") or "").lower(),
                        )
                        if component
                    }
                    fact_name = str(fields.get("name") or "").lower()
                    if "deepflow" in source_components:
                        deepflow_facts.append(fields)
                    if (
                        "tempo" in source_components
                        and (
                            source_components == {"tempo"}
                            or "span" in fact_name
                        )
                    ):
                        tempo_facts.append(fields)
            elif line.startswith("- CANONICAL_FACT "):
                fields = expand_structured_value(parse_fields(line))
                if str(fields.get("dimension") or "").strip().lower() == "kubernetes":
                    k8s_facts.append(fields)
                    tool = str(fields.get("tool") or "").strip()
                    if tool:
                        source_states["kubernetes"][tool] = "present"

        if not (
            coverage_present
            or metric_facts
            or log_facts
            or k8s_facts
            or deepflow_facts
            or tempo_facts
            or execution_fields
        ):
            return content
        if execution_fields and not (
            coverage_present
            or metric_facts
            or log_facts
            or k8s_facts
            or deepflow_facts
            or tempo_facts
        ):
            return enforce_unexecuted_rows(content, execution_fields)

        do_not_merge = any(
            str(item.get("do_not_merge") or "").lower() == "true"
            for item in correlations
        )
        signals: List[str] = []
        evidence_refs: List[str] = []

        if do_not_merge:
            source_ids = []
            for item in correlations:
                for key in (
                    "log_trace_ids",
                    "tempo_trace_ids",
                    "deepflow_trace_ids",
                    "log_tempo_trace_ids",
                ):
                    value = item.get(key)
                    if value:
                        source_ids.append(f"{key}={value}")
            warning = "来源 Trace ID 不一致，禁止跨 ID 合并"
            if source_ids:
                warning += "：" + ", ".join(dict.fromkeys(source_ids))
            signals.append(warning)

        for fact in deepflow_facts:
            parts = []
            if fact.get("trace_id"):
                parts.append(f"trace_id={fact['trace_id']}")
            for key in ("request", "response_code", "duration_us"):
                if fact.get(key):
                    parts.append(f"{key}={fact[key]}")
            if parts:
                signals.append("DeepFlow " + " ".join(parts))
            evidence_ref = fact.get("evidence_ref") or fact.get("ref")
            if evidence_ref:
                evidence_refs.append(evidence_ref)

        tempo_detail_keys = (
            "http.response.status_code",
            "error.type",
            "config.key",
            "config.present",
            "aiops.allocated_mib.before",
            "aiops.allocated_mib.after",
            "aiops.alloc_mib",
            "url.path",
        )
        for fact in tempo_facts:
            parts = []
            if fact.get("trace_id"):
                parts.append(f"trace_id={fact['trace_id']}")
            for key in ("service", "span"):
                if fact.get(key):
                    parts.append(f"{key}={fact[key]}")
            for key in tempo_detail_keys:
                if fact.get(key):
                    parts.append(f"{key}={fact[key]}")
            if parts:
                signals.append("Tempo " + " ".join(parts))
            evidence_ref = fact.get("evidence_ref") or fact.get("ref")
            if evidence_ref:
                evidence_refs.append(evidence_ref)

        if not signals:
            signals.append("结构化 coverage 标记 tracing/trace=present")

        def table_cell(values: List[str]) -> str:
            return "<br>".join(
                value.replace("|", r"\|")
                for value in dict.fromkeys(values)
                if value
            )

        def source_cell(dimension: str, fallback: str) -> str:
            tools = [
                tool
                for tool, state in source_states.get(dimension, {}).items()
                if state != "not_executed"
            ]
            if not tools:
                return fallback
            return f"{fallback} ({', '.join(f'`{tool}`' for tool in tools)})"

        metric_signals: List[str] = []
        metric_refs: List[str] = []
        metric_keys = (
            "metric",
            "name",
            "value",
            "unit",
            "pod",
            "container",
            "start",
            "max",
            "last",
            "limit",
            "max_limit_ratio",
            "samples",
            "sample_count",
            "trend_evaluable",
            "series_role",
            "stats",
        )
        for fact in metric_facts:
            parts = [f"{key}={fact[key]}" for key in metric_keys if fact.get(key)]
            if parts:
                metric_signals.append(" ".join(parts))
            ref = fact.get("evidence_ref") or fact.get("ref")
            if ref:
                metric_refs.append(ref)

        log_signals: List[str] = []
        log_refs: List[str] = []
        log_keys = (
            "role",
            "event",
            "level",
            "message",
            "error_code",
            "pod",
            "path",
            "trace_id",
            "value",
        )
        for fact in log_facts:
            parts = [f"{key}={fact[key]}" for key in log_keys if fact.get(key)]
            if parts:
                log_signals.append(" ".join(parts))
            ref = fact.get("evidence_ref") or fact.get("ref")
            if ref:
                log_refs.append(ref)

        k8s_signals: List[str] = []
        k8s_refs: List[str] = []
        for fact in k8s_facts:
            if fact.get("observed"):
                k8s_signals.append(fact["observed"])
            else:
                parts = [
                    f"{key}={fact[key]}"
                    for key in ("entity_id", "attribute", "value")
                    if fact.get(key)
                ]
                if parts:
                    k8s_signals.append(" ".join(parts))
            raw_refs = fact.get("evidence_refs")
            if raw_refs:
                try:
                    parsed_refs = json.loads(raw_refs)
                except (json.JSONDecodeError, TypeError):
                    parsed_refs = []
                if isinstance(parsed_refs, list):
                    k8s_refs.extend(str(ref) for ref in parsed_refs if ref)
            fact_ref = fact.get("ref") or fact.get("fact_id")
            if fact_ref:
                k8s_refs.append(str(fact_ref))

        tracing_row = (
            f"| **Tracing** | {source_cell('tracing', 'DeepFlow/Tempo')} | present | "
            f"{table_cell(signals)} | "
            f"{table_cell(evidence_refs) or '见机器可核验附录'} |"
        )
        exact_rows = {
            "metrics": (
                f"| **Metrics** | {source_cell('metrics', 'Prometheus')} | "
                f"{coverage_fields.get('metrics') or 'present'} | "
                f"{table_cell(metric_signals) or '未返回可用指标样本'} | "
                f"{table_cell(metric_refs) or '见机器可核验附录'} |"
            ),
            "logging": (
                f"| **Logging** | {source_cell('logging', 'ES/Filebeat')} | "
                f"{coverage_fields.get('logs') or 'present'} | "
                f"{table_cell(log_signals) or '未返回可用日志原文'} | "
                f"{table_cell(log_refs) or '见机器可核验附录'} |"
            ),
            "tracing": tracing_row,
            "k8s": (
                f"| **K8s** | {source_cell('kubernetes', 'Kubernetes API')} | "
                f"{coverage_fields.get('k8s') or 'present'} | "
                f"{table_cell(k8s_signals) or '未返回可用 Kubernetes 强信号'} | "
                f"{table_cell(k8s_refs) or '见机器可核验附录'} |"
            ),
        }
        lines = content.splitlines()
        section_start = next(
            (
                index for index, line in enumerate(lines)
                if re.match(r"^###\s+三大观测维度\s*$", line.strip())
            ),
            None,
        )
        if section_start is None:
            supported_dimensions = {
                dimension
                for dimension, supported in {
                    "metrics": bool(metric_facts or coverage_fields.get("metrics")),
                    "logging": bool(log_facts or coverage_fields.get("logs")),
                    "tracing": bool(
                        deepflow_facts
                        or tempo_facts
                        or coverage_present
                    ),
                    "k8s": bool(k8s_facts or coverage_fields.get("k8s")),
                }.items()
                if supported
            }
            dimension_rows = {
                "metrics": exact_rows["metrics"],
                "logging": exact_rows["logging"],
                "tracing": exact_rows["tracing"],
                "k8s": exact_rows["k8s"],
            }
            replaced = False
            for index, line in enumerate(lines):
                match = re.match(
                    r"^\|\s*\*{0,2}(metrics|logging|tracing|k8s)\*{0,2}\s*\|",
                    line.strip(),
                    re.IGNORECASE,
                )
                if not match:
                    continue
                dimension = match.group(1).lower()
                if dimension not in supported_dimensions:
                    continue
                lines[index] = dimension_rows[dimension]
                replaced = True
            if not replaced:
                return content
            result = "\n".join(lines)
            if content.endswith("\n"):
                result += "\n"
            return result
        section_end = next(
            (
                index for index in range(section_start + 1, len(lines))
                if re.match(r"^#{1,3}\s+", lines[index].strip())
            ),
            len(lines),
        )

        dimension_row_pattern = re.compile(
            r"^\|\s*\*{0,2}(?:metrics|logging|tracing|k8s)\*{0,2}\s*\|",
            re.IGNORECASE,
        )
        for index in reversed(range(section_start + 1, min(section_end, len(lines)))):
            if dimension_row_pattern.match(lines[index].strip()):
                del lines[index]

        section_end = next(
            (
                index for index in range(section_start + 1, len(lines))
                if re.match(r"^#{1,3}\s+", lines[index].strip())
            ),
            len(lines),
        )
        separator_index = next(
            (
                index
                for index in range(section_start + 1, section_end)
                if lines[index].strip().startswith("|")
                and set(lines[index].replace("|", "").strip()) <= {"-", ":", " "}
            ),
            None,
        )
        if separator_index is None:
            return content
        canonical_rows = [
            exact_rows["metrics"],
            exact_rows["logging"],
            exact_rows["tracing"],
            exact_rows["k8s"],
        ]
        lines[separator_index + 1:separator_index + 1] = canonical_rows

        result = "\n".join(lines)
        if content.endswith("\n"):
            result += "\n"
        return enforce_unexecuted_rows(result, execution_fields)

    @staticmethod
    def _source_tools_for_dimension(
        structured_context: str,
        dimension: str,
    ) -> List[str]:
        tools: List[str] = []
        for raw_line in str(structured_context or "").splitlines():
            line = raw_line.strip()
            if line.startswith("OBSERVABILITY_SOURCE "):
                dimension_match = re.search(r"\bdimension=(\S+)", line)
                tool_match = re.search(r"\btool=(\S+)", line)
                if (
                    dimension_match
                    and tool_match
                    and dimension_match.group(1).strip().lower()
                    == dimension.strip().lower()
                ):
                    tools.append(tool_match.group(1))
            elif line.startswith("- CANONICAL_FACT "):
                dimension_match = re.search(r"\bdimension=(\S+)", line)
                tool_match = re.search(r"\btool=(\S+)", line)
                if (
                    dimension_match
                    and tool_match
                    and dimension_match.group(1).strip().lower()
                    == dimension.strip().lower()
                ):
                    tools.append(tool_match.group(1))
        if tools:
            return list(dict.fromkeys(tools))
        if "observability_collection_mode: coarse_case" in str(
            structured_context or ""
        ):
            return ["collect_aiops_case"]
        return []

    @classmethod
    def _provenance_label(
        cls,
        structured_context: str,
        dimensions: tuple[str, ...],
        *,
        fallback: str,
    ) -> str:
        tools = [
            tool
            for dimension in dimensions
            for tool in cls._source_tools_for_dimension(
                structured_context,
                dimension,
            )
        ]
        tools = list(dict.fromkeys(tools))
        if not tools:
            return fallback
        return "、".join(f"`{tool}`" for tool in tools)

